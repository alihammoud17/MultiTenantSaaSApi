#!/usr/bin/env bash
# Local systemd test host for the full playbook (Floci instances can't run services).
#   scripts/test-host.sh up     build and start the container, write inventories/test
#   scripts/test-host.sh down   remove the container
# Then: ansible-playbook -i inventories/test playbooks/site.yml
# NGINX is published on http://localhost:${TEST_HTTP_PORT:-8088}.
set -euo pipefail

here="$(cd "$(dirname "$0")/.." && pwd)"
name=mtsaas-ansible-test
image=mtsaas-ansible-test:debian12
ssh_port="${TEST_SSH_PORT:-2222}"
http_port="${TEST_HTTP_PORT:-8088}"
key="$here/tests/systemd-host/id_ed25519"
inv="$here/inventories/test"

case "${1:-}" in
  up)
    [ -f "$key" ] || ssh-keygen -q -t ed25519 -N '' -C "$name" -f "$key"
    docker build --platform linux/amd64 -t "$image" "$here/tests/systemd-host"
    docker rm -f "$name" >/dev/null 2>&1 || true
    docker run -d --name "$name" --platform linux/amd64 --privileged --cgroupns=host \
      -v /sys/fs/cgroup:/sys/fs/cgroup:rw --tmpfs /run --tmpfs /run/lock \
      -p "127.0.0.1:$ssh_port:22" -p "127.0.0.1:$http_port:80" "$image" >/dev/null
    docker cp "$key.pub" "$name:/root/.ssh/authorized_keys"
    docker exec "$name" sh -c 'chown root:root /root/.ssh/authorized_keys && chmod 600 /root/.ssh/authorized_keys'
    # Test-host only: nested Docker can't create the user namespace Debian's Redis unit asks for
    # (PrivateUsers=true). EC2 instances can, so the role itself doesn't change this.
    docker exec "$name" sh -c 'mkdir -p /etc/systemd/system/redis-server.service.d &&
      printf "[Service]\nPrivateUsers=false\n" > /etc/systemd/system/redis-server.service.d/test-host.conf'

    cat > "$inv/hosts.yml" <<YAML
---
# Generated by scripts/test-host.sh. Do not commit.
all:
  children:
    app:
      hosts:
        app1:
          ansible_host: 127.0.0.1
          ansible_port: $ssh_port
          ansible_user: root
          ansible_ssh_private_key_file: $key
          ansible_ssh_common_args: "-o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null"
YAML

    # Throwaway secrets for a disposable container, generated per run and git-ignored.
    if [ ! -f "$inv/group_vars/all/vault.yml" ]; then
      r() { openssl rand -hex 32; }
      cat > "$inv/group_vars/all/vault.yml" <<YAML
---
vault_db_password: $(r)
vault_redis_password: $(r)
vault_jwt_secret: $(r)
vault_billing_shared_secret: $(r)
vault_tenant_operations_shared_secret: ""
vault_webhook_signing_secret: $(r)
vault_stripe_api_key: ""
YAML
    fi
    echo "test host up: ssh root@127.0.0.1 -p $ssh_port -i $key; http://localhost:$http_port"
    ;;
  down)
    docker rm -f "$name" >/dev/null 2>&1 || true
    echo "test host removed"
    ;;
  *)
    echo "usage: $0 up|down" >&2
    exit 2
    ;;
esac
