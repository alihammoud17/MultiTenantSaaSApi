#!/usr/bin/env bash
# Writes inventories/<floci|aws>/hosts.yml from the Terraform outputs.
#   scripts/inventory.sh floci|aws [private-key-path]
# TF_BIN selects the CLI (default: tofu). The key defaults to ~/.ssh/mtsaas-ansible.
set -euo pipefail

target="${1:?usage: $0 floci|aws [private-key-path]}"
key="${2:-$HOME/.ssh/mtsaas-ansible}"
tf="${TF_BIN:-tofu}"
here="$(cd "$(dirname "$0")/.." && pwd)"
tf_dir="$here/../terraform"

output() { "$tf" -chdir="$tf_dir" output -raw "$1"; }

instance_id="$(output app_instance_id)"
user="$(output ansible_user)"

case "$target" in
  floci)
    # Floci runs the instance as a container and publishes its sshd on a local port.
    port="$(docker port "floci-aws-ec2-$instance_id" 22 | head -n1 | awk -F: '{print $NF}')"
    host=127.0.0.1
    # Each Floci instance gets fresh host keys on a reused local port.
    ssh_args="-o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null"
    ;;
  aws)
    port=22
    host="$(output app_instance_public_ip)"
    ssh_args="-o StrictHostKeyChecking=accept-new"
    ;;
  *)
    echo "unknown target: $target (expected floci or aws)" >&2
    exit 2
    ;;
esac

out="$here/inventories/$target/hosts.yml"
cat > "$out" <<YAML
---
# Generated by scripts/inventory.sh for $instance_id. Do not commit.
all:
  children:
    app:
      hosts:
        app1:
          ansible_host: $host
          ansible_port: $port
          ansible_user: $user
          ansible_ssh_private_key_file: $key
          ansible_ssh_common_args: "$ssh_args"
YAML
echo "wrote $out ($user@$host:$port)"
